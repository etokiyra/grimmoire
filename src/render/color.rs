//! The renderer's terminal-independent colour palette.
//!
//! Drawing code only ever refers to [`Color`]; the terminal backend is the sole
//! place that translates these values into concrete escape sequences. This keeps
//! frame composition free of any backend dependency and easy to test.

/// A colour that can be applied to a cell's foreground or background.
///
/// The named variants mirror the classic 16-colour ANSI palette. `Light*`
/// variants are the bright/high-intensity versions of their base colour.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Color {
    /// Leave the terminal's configured default colour in place.
    #[default]
    Default,
    /// Standard black.
    Black,
    /// Standard red.
    Red,
    /// Standard green.
    Green,
    /// Standard yellow.
    Yellow,
    /// Standard blue.
    Blue,
    /// Standard magenta.
    Magenta,
    /// Standard cyan.
    Cyan,
    /// Standard white (the "light grey" slot on most terminals).
    White,
    /// Bright black / dark grey.
    DarkGrey,
    /// Bright red.
    LightRed,
    /// Bright green.
    LightGreen,
    /// Bright yellow.
    LightYellow,
    /// Bright blue.
    LightBlue,
    /// Bright magenta.
    LightMagenta,
    /// Bright cyan.
    LightCyan,
    /// A colour from the terminal's 256-colour palette.
    Indexed(u8),
    /// A 24-bit truecolour value.
    Rgb(u8, u8, u8),
}

/// The sixteen classic colours, in the order their indices run.
const BASIC: [(Color, u8, u8, u8); 16] = [
    (Color::Black, 0, 0, 0),
    (Color::Red, 170, 0, 0),
    (Color::Green, 0, 170, 0),
    (Color::Yellow, 170, 85, 0),
    (Color::Blue, 0, 0, 170),
    (Color::Magenta, 170, 0, 170),
    (Color::Cyan, 0, 170, 170),
    (Color::White, 170, 170, 170),
    (Color::DarkGrey, 85, 85, 85),
    (Color::LightRed, 255, 85, 85),
    (Color::LightGreen, 85, 255, 85),
    (Color::LightYellow, 255, 255, 85),
    (Color::LightBlue, 85, 85, 255),
    (Color::LightMagenta, 255, 85, 255),
    (Color::LightCyan, 85, 255, 255),
    (Color::Default, 255, 255, 255),
];

impl Color {
    /// Reduces a colour to the closest of the sixteen classic ones.
    ///
    /// The game's art is authored once, in 256 colours, and reduced where the
    /// terminal cannot do better. One definition per character that degrades, in
    /// other words, rather than two that can drift apart.
    #[must_use]
    pub fn nearest_basic(self) -> Color {
        let Some((r, g, b)) = self.as_rgb() else {
            return self;
        };
        let mut best = Color::White;
        let mut best_distance = u32::MAX;
        for (colour, cr, cg, cb) in BASIC {
            let distance = squared_distance(r, g, b, cr, cg, cb);
            if distance < best_distance {
                best_distance = distance;
                best = colour;
            }
        }
        best
    }

    /// The 24-bit value a colour stands for, if it has one.
    ///
    /// The classic sixteen are the usual VGA values, and the 256-colour palette
    /// is generated by the rule every terminal uses: a 6×6×6 cube from index 16,
    /// then twenty-four greys.
    #[must_use]
    pub fn as_rgb(self) -> Option<(u8, u8, u8)> {
        match self {
            Color::Default => None,
            Color::Rgb(r, g, b) => Some((r, g, b)),
            Color::Indexed(index) if index < 16 => {
                let (_, r, g, b) = BASIC[usize::from(index)];
                Some((r, g, b))
            }
            Color::Indexed(index) if index < 232 => {
                let cube = u32::from(index) - 16;
                let steps = [0u8, 95, 135, 175, 215, 255];
                let r = steps[(cube / 36) as usize];
                let g = steps[((cube / 6) % 6) as usize];
                let b = steps[(cube % 6) as usize];
                Some((r, g, b))
            }
            Color::Indexed(index) => {
                let level = 8 + 10 * (u32::from(index) - 232).min(23);
                let level = level as u8;
                Some((level, level, level))
            }
            other => BASIC
                .iter()
                .find(|(colour, ..)| *colour == other)
                .map(|(_, r, g, b)| (*r, *g, *b)),
        }
    }
}

/// How far apart two colours are, weighted the way an eye weighs them.
fn squared_distance(r: u8, g: u8, b: u8, cr: u8, cg: u8, cb: u8) -> u32 {
    let dr = i32::from(r) - i32::from(cr);
    let dg = i32::from(g) - i32::from(cg);
    let db = i32::from(b) - i32::from(cb);
    (3 * dr * dr + 6 * dg * dg + 2 * db * db) as u32
}

#[cfg(test)]
mod palette_tests {
    use super::Color;

    #[test]
    fn the_256_colour_palette_decodes_the_way_terminals_do() {
        assert_eq!(Some((0, 0, 0)), Color::Indexed(16).as_rgb());
        assert_eq!(Some((255, 0, 0)), Color::Indexed(196).as_rgb());
        assert_eq!(Some((255, 255, 255)), Color::Indexed(231).as_rgb());
        assert_eq!(Some((128, 128, 128)), Color::Indexed(244).as_rgb());
        assert_eq!(Some((255, 0, 0)), Color::Rgb(255, 0, 0).as_rgb());
        assert_eq!(None, Color::Default.as_rgb());
    }

    #[test]
    fn a_colour_reduces_to_the_nearest_classic_one() {
        // Vivid 256-colour values land on their obvious sixteen-colour cousins.
        assert_eq!(Color::Red, Color::Indexed(196).nearest_basic());
        assert_eq!(Color::LightRed, Color::Indexed(203).nearest_basic());
        assert_eq!(Color::Black, Color::Indexed(233).nearest_basic());
        assert_eq!(Color::LightCyan, Color::Indexed(51).nearest_basic());
        assert_eq!(Color::LightYellow, Color::Indexed(220).nearest_basic());
        // A colour that is already classic is left alone.
        assert_eq!(Color::LightMagenta, Color::LightMagenta.nearest_basic());
    }

    #[test]
    fn a_default_colour_stays_default() {
        assert_eq!(Color::Default, Color::Default.nearest_basic());
    }
}
